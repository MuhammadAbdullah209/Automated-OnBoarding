using System.ComponentModel.DataAnnotations;

namespace AOB.BAL.Entities
{
    /// <summary>
    /// A file a customer uploaded, normally for a document type. There is at most one per customer
    /// and document type: uploading again replaces the earlier file. Documents without a type
    /// (DocumentTypeId null) are not limited to one.
    /// </summary>
    public class CustomerDocument
    {
        [Key]
        public Guid Id { get; set; } = Guid.NewGuid();

        public Guid CustomerId { get; set; }

        // Optional: null means the document is not tied to any document type.
        public Guid? DocumentTypeId { get; set; }

        // Name the customer's file had, shown back to them and used for downloads.
        [Required, MaxLength(260)]
        public string OriginalFileName { get; set; } = string.Empty;

        // Where the file lives in file storage (generated by us, never from user input).
        [Required, MaxLength(300)]
        public string StoredFilePath { get; set; } = string.Empty;

        [MaxLength(150)]
        public string? ContentType { get; set; }

        public long FileSizeBytes { get; set; }

        public DateTimeOffset UploadedAt { get; set; } = DateTimeOffset.UtcNow;

        public Customer Customer { get; set; } = null!;

        public DocumentType? DocumentType { get; set; }
    }
}
