using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using AOB.BAL.Common.Enums;

namespace AOB.BAL.Entities
{
    /// <summary>
    /// A file uploaded to a project. Stored with FileCategory.ProjectDocument through IFileStorage,
    /// so the file lives under the "project-documents" folder, in a sub-folder per project.
    /// </summary>
    public class ProjectDocument
    {
        [Key]
        public Guid Id { get; set; } = Guid.NewGuid();

        [ForeignKey(nameof(Project))]
        public Guid ProjectId { get; set; }

        // What kind of document this is (see ProjectDocumentType).
        public ProjectDocumentType Type { get; set; }

        // Name the uploaded file had, shown back to the user and used for downloads.
        [Required, MaxLength(260)]
        public string OriginalFileName { get; set; } = string.Empty;

        // Where the file lives in file storage (generated by us, never from user input).
        [Required, MaxLength(300)]
        public string StoredFilePath { get; set; } = string.Empty;

        [MaxLength(150)]
        public string? ContentType { get; set; }

        public long FileSizeBytes { get; set; }

        // Set when the file was uploaded to answer an item of an information request.
        public Guid? InformationRequestItemId { get; set; }

        public DateTimeOffset UploadedAt { get; set; } = DateTimeOffset.UtcNow;

        public Project Project { get; set; } = null!;
    }
}
